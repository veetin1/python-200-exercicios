numero1 = 19
numero2 = 9

def operacoes():
    resultado_soma = numero1 + numero2
    print(resultado_soma)
    resultado_subtracao = numero1 - numero2
    print(resultado_subtracao)
    resultado_multiplicacao = numero1 * numero2
    print(resultado_multiplicacao)
    resultado_divisao = numero1 // numero2  # divisão inteira
    print(resultado_divisao)
    resultado_resto = numero1 % numero2
    print(resultado_resto)

if __name__ == '__main__':
    operacoes()